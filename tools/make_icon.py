"""Builds OpenRasa's icon files from the SVG masters in packaging/icon (run again only when the artwork changes; the outputs are committed).

    python tools/make_icon.py

Writes packaging/icon/openrasa-<size>.png (16 24 32 48 64 128 256), packaging/icon/openrasa.ico (every size, PNG-compressed entries)
and src/AppIcon.h (the PNGs the window icon is made from). Sizes up to 32 come from openrasa-small.svg, the others from openrasa.svg.
Needs Windows with Microsoft Edge (its headless mode renders the SVGs) and Python with Pillow.
"""
import os
import struct
import subprocess
import sys
import tempfile
import time

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ICON = os.path.join(ROOT, "packaging", "icon")
SIZES = [16, 24, 32, 48, 64, 128, 256]
WINDOW_SIZES = [16, 32, 64, 128]            # embedded for SDL_SetWindowIcon (64 as the main image, the others alternates)


def find_edge():
    for base in (os.environ.get("ProgramFiles(x86)"), os.environ.get("ProgramFiles"), os.environ.get("LOCALAPPDATA")):
        if base:
            path = os.path.join(base, "Microsoft", "Edge", "Application", "msedge.exe")
            if os.path.exists(path):
                return path
    sys.exit("Microsoft Edge was not found (it renders the SVGs).")


def render(edge, svg, size, out_png):
    # The SVG drawn at the top left of a transparent page, captured with a transparent background and cropped to the size.
    with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as tmp:   # Edge may still hold its profile
        html = os.path.join(tmp, "icon.html")
        with open(html, "w", encoding="utf-8") as f:
            f.write('<html><body style="margin:0;background:transparent">'
                    f'<img src="file:///{svg.replace(os.sep, "/")}" width="{size}" height="{size}" style="display:block"></body></html>')
        shot = os.path.join(tmp, "shot.png")
        # Its own profile folder, so the capture runs in a new browser process (not handed to an Edge already running).
        subprocess.run([edge, "--headless=new", "--disable-gpu", "--hide-scrollbars", "--force-device-scale-factor=1",
                        f"--user-data-dir={os.path.join(tmp, 'profile')}", "--no-first-run",
                        "--default-background-color=00000000", "--window-size=300,300", f"--screenshot={shot}",
                        "file:///" + html.replace(os.sep, "/")], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=120)
        for _ in range(100):
            if os.path.exists(shot) and os.path.getsize(shot) > 0:
                break
            time.sleep(0.1)
        else:
            sys.exit(f"Edge wrote no screenshot for {svg} at {size} px.")
        time.sleep(0.2)
        Image.open(shot).convert("RGBA").crop((0, 0, size, size)).save(out_png, optimize=True)


def write_ico(pngs, out_ico):
    # ICONDIR + one ICONDIRENTRY per image, each image stored as PNG data (Windows Vista and later).
    data = [open(p, "rb").read() for _, p in pngs]
    offset = 6 + 16 * len(pngs)
    with open(out_ico, "wb") as f:
        f.write(struct.pack("<HHH", 0, 1, len(pngs)))
        for (size, _), blob in zip(pngs, data):
            dim = 0 if size >= 256 else size
            f.write(struct.pack("<BBBBHHII", dim, dim, 0, 0, 1, 32, len(blob), offset))
            offset += len(blob)
        for blob in data:
            f.write(blob)


def write_header(pngs, out_h):
    lines = ["// Generated by tools/make_icon.py from packaging/icon/*.svg - do not edit.",
             "// The window icon (SDL_SetWindowIcon): PNG images by size.", "#pragma once", "#include <cstddef>", "#include <cstdint>", "",
             "namespace appicon {", "struct Image { int size; const uint8_t* png; size_t bytes; };"]
    names = []
    for size, path in pngs:
        blob = open(path, "rb").read()
        name = f"png{size}"
        names.append((size, name, len(blob)))
        lines.append(f"inline const uint8_t {name}[] = {{")
        for i in range(0, len(blob), 24):
            lines.append("    " + ", ".join(str(b) for b in blob[i:i + 24]) + ",")
        lines.append("};")
    lines.append("inline const Image images[] = {")
    for size, name, n in names:
        lines.append(f"    {{{size}, {name}, {n}}},")
    lines.append("};")
    lines.append("}  // namespace appicon")
    with open(out_h, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


def main():
    edge = find_edge()
    pngs = []
    for size in SIZES:
        svg = os.path.join(ICON, "openrasa-small.svg" if size <= 32 else "openrasa.svg")
        out = os.path.join(ICON, f"openrasa-{size}.png")
        render(edge, svg, size, out)
        pngs.append((size, out))
        print("wrote", out)
    write_ico(pngs, os.path.join(ICON, "openrasa.ico"))
    print("wrote", os.path.join(ICON, "openrasa.ico"))
    write_header([p for p in pngs if p[0] in WINDOW_SIZES], os.path.join(ROOT, "src", "AppIcon.h"))
    print("wrote", os.path.join(ROOT, "src", "AppIcon.h"))


if __name__ == "__main__":
    main()
